import pdfMake from 'pdfmake/build/pdfmake';
import pdfFonts from 'pdfmake/build/vfs_fonts';
pdfMake.vfs = pdfFonts.pdfMake ? pdfFonts.pdfMake.vfs : pdfFonts;

export function exportToPdf(dashboardData) {
  const {
    title = 'Dashboard Report',
    standfirst = '',
    summary = [],
    kpis = [],
    narrative = '',
    watchList = [],
    metadata = {},
  } = dashboardData;

  const today = new Date().toLocaleDateString('en-GB', {
    day: 'numeric', month: 'long', year: 'numeric',
  });

  const styles = {
    coverTitle:    { fontSize: 28, bold: true, color: '#1E293B', margin: [0, 0, 0, 12] },
    coverSubtitle: { fontSize: 14, color: '#475569', margin: [0, 0, 0, 8] },
    coverMeta:     { fontSize: 11, color: '#94A3B8' },
    sectionHeader: { fontSize: 14, bold: true, color: '#2563EB', margin: [0, 24, 0, 10] },
    bodyText:      { fontSize: 11, color: '#334155', lineHeight: 1.6 },
    bulletText:    { fontSize: 11, color: '#334155', margin: [0, 2, 0, 2] },
    kpiLabel:      { fontSize: 10, color: '#64748B', bold: true },
    kpiValue:      { fontSize: 16, bold: true, color: '#1E293B' },
    watchItem:     { fontSize: 11, color: '#334155', margin: [0, 3, 0, 3] },
    footer:        { fontSize: 9, color: '#94A3B8' },
  };

  // KPI table — 2 per row
  const kpiRows = [];
  for (let i = 0; i < kpis.length; i += 2) {
    const left  = kpis[i];
    const right = kpis[i + 1];
    const makeCell = (kpi) => ({
      stack: [
        { text: kpi?.label || '', style: 'kpiLabel' },
        { text: kpi?.value !== undefined ? String(kpi.value) : '', style: 'kpiValue' },
        kpi?.delta ? { text: kpi.delta, fontSize: 10, color: kpi?.deltaPositive ? '#16A34A' : '#DC2626' } : {},
      ],
      fillColor: '#F8FAFC',
      margin: [10, 10, 10, 10],
      border: [false, false, false, false],
    });

    kpiRows.push([
      makeCell(left),
      right ? makeCell(right) : { text: '', border: [false, false, false, false] },
    ]);
  }

  // Watch list — watchList items are { type, text } from Claude schema
  const watchItems = (watchList || []).map(item => ({
    text: `• ${item?.text || item?.title || item?.label || String(item)}`,
    style: 'watchItem',
  }));

  // Summary — array of strings
  const summaryItems = (summary || []).map(s => ({
    text: `• ${typeof s === 'string' ? s : s?.point || s?.text || JSON.stringify(s)}`,
    style: 'bulletText',
  }));

  const docDefinition = {
    pageSize: 'A4',
    pageMargins: [50, 70, 50, 60],

    header: (currentPage) => currentPage === 1 ? {} : {
      columns: [
        { text: title, style: 'footer', margin: [50, 20, 0, 0] },
        { text: `Page ${currentPage}`, style: 'footer', alignment: 'right', margin: [0, 20, 50, 0] },
      ],
    },

    footer: {
      columns: [
        { text: 'Generated by DocDash · docdash-dusky.vercel.app', style: 'footer', margin: [50, 0, 0, 0] },
        { text: today, style: 'footer', alignment: 'right', margin: [0, 0, 50, 0] },
      ],
    },

    content: [
      // Blue accent bar
      { canvas: [{ type: 'rect', x: 0, y: 0, w: 495, h: 4, r: 2, color: '#2563EB' }], margin: [0, 0, 0, 24] },
      { text: title, style: 'coverTitle' },
      standfirst ? { text: standfirst, style: 'coverSubtitle' } : {},
      { text: `Generated ${today}`, style: 'coverMeta' },
      metadata?.source ? { text: `Source: ${metadata.source}`, style: 'coverMeta', margin: [0, 2, 0, 0] } : {},

      // Executive Summary
      summaryItems.length > 0 ? [
        { text: 'Executive Summary', style: 'sectionHeader' },
        ...summaryItems,
      ] : [],

      // Key Metrics
      kpiRows.length > 0 ? [
        { text: 'Key Metrics', style: 'sectionHeader' },
        {
          table: { widths: ['*', '*'], body: kpiRows },
          layout: { hLineWidth: () => 0, vLineWidth: () => 0, paddingLeft: () => 0, paddingRight: () => 0 },
        },
      ] : [],

      // Analysis
      narrative ? [
        { text: 'Analysis', style: 'sectionHeader' },
        { text: narrative, style: 'bodyText' },
      ] : [],

      // Watch List
      watchItems.length > 0 ? [
        { text: 'Executive Watch List', style: 'sectionHeader' },
        ...watchItems,
      ] : [],

      // Footer rule
      { canvas: [{ type: 'line', x1: 0, y1: 10, x2: 495, y2: 10, lineWidth: 1, lineColor: '#E2E8F0' }], margin: [0, 20, 0, 0] },
      { text: 'This report was auto-generated by DocDash using AI analysis. Verify figures against source data before use in formal reporting.', style: 'footer', margin: [0, 8, 0, 0] },
    ].flat(),

    styles,
  };

  const safeTitle = (title || 'dashboard').replace(/[^a-z0-9]/gi, '-').toLowerCase();
  pdfMake.createPdf(docDefinition).download(`${safeTitle}-report.pdf`);
}
